def supported(code: str | None) -> str | None:
    """A Telegram ``language_code`` ("pt-br", "zh-hans", "fa") as one of the bot's languages, or None."""
    if not code:
        return None
    base = code.lower().replace("_", "-").split("-")[0]
    return base if base in LANGUAGES else None
